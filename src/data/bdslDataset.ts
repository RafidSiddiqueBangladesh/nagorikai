/**
 * Deterministic local matcher that converts arbitrary Bangla/English input into BdSL sequence steps
 * using longest-phrase matching against all PDF signs + letter fallback.
 */
export function buildLocalSignSequence(input: string): SignSequenceStep[] {
  const cleaned = input
    .trim()
    .replace(/[।,!?."';:()]/g, ' ')
    .replace(/\s+/g, ' ');
  if (!cleaned) return [];

  const lower = cleaned.toLowerCase();
  const words = lower.split(' ').filter(Boolean);
  const steps: SignSequenceStep[] = [];
  const searchable = [...BDSL_VOCABULARY, ...BDSL_NUMBERS];

  let i = 0;
  while (i < words.length) {
    let matched: BdslSign | undefined;
    let span = 1;

    // Try 3-word, then 2-word, then 1-word phrases
    for (const trySpan of [3, 2, 1]) {
      if (i + trySpan > words.length) continue;
      const phrase = words.slice(i, i + trySpan).join(' ');
      matched = searchable.find(
        (sign) =>
          sign.bangla.toLowerCase() === phrase ||
          sign.english.toLowerCase() === phrase ||
          sign.synonyms.some((syn) => syn.toLowerCase() === phrase),
      );
      if (matched) {
        span = trySpan;
        break;
      }
    }

    // Partial/stem check for common Bangla inflections (e.g. তোমাকে -> তুমি, আমার -> আমার)
    if (!matched) {
      const w = words[i];
      matched = searchable.find((sign) =>
        sign.synonyms.some((syn) => w.includes(syn.toLowerCase()) && syn.length >= 2),
      );
    }

    if (matched) {
      steps.push({
        id: `step_${Date.now()}_${i}_${matched.id}`,
        sign: matched,
        spokenToken: words.slice(i, i + span).join(' '),
        explanationBn: matched.pdfDescription,
        explanationEn: matched.englishExplanation,
      });
      i += span;
      continue;
    }

    // Fallback: fingerspell ASCII letters or represent unknown Bangla word clearly
    const token = words[i];
    const asciiLetters = token.replace(/[^a-z0-9]/gi, '');
    if (asciiLetters.length > 0 && asciiLetters.length <= 6) {
      for (const ch of asciiLetters.toUpperCase()) {
        const letterSign =
          BDSL_ALPHABETS.find((a) => a.synonyms.includes(ch)) ||
          BDSL_NUMBERS.find((n) => n.synonyms.includes(ch));
        if (letterSign) {
          steps.push({
            id: `step_${Date.now()}_${i}_${ch}`,
            sign: letterSign,
            spokenToken: `${token} (${ch})`,
            explanationBn: letterSign.pdfDescription,
            explanationEn: letterSign.englishExplanation,
          });
        }
      }
    } else {
      // Represent unknown word with 'কথা বলা' (Speak) + 'তথ্য/খবর' contextual gloss
      const fallbackSign = BDSL_VOCABULARY.find((s) => s.id === 'kotha_bola')!;
      steps.push({
        id: `step_${Date.now()}_${i}_custom`,
        sign: {
          ...fallbackSign,
          id: `custom_${i}`,
          bangla: token,
          english: token,
          pdfDescription: `"${token}" — ${fallbackSign.pdfDescription}`,
          englishExplanation: `Sign expression for "${token}" using index speech gesture.`,
        },
        spokenToken: token,
        explanationBn: `"${token}" শব্দের ইশারা: ${fallbackSign.pdfDescription}`,
        explanationEn: `Expressing "${token}" in Bangla Sign Language.`,
      });
    }

    i += 1;
  }

  return steps;
}
